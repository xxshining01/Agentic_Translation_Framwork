class PluginASTParser:
    """
    โมดูลจัดการการแยกและประกอบ JavaScript Wrapper สำหรับ www/js/plugins.js (SDD-015 Section 2)
    """
    HEADER_TEMPLATE: str = (
        "// Generated by RPG Maker.\n"
        "// Do not edit this file directly.\n"
        "var $plugins =\n"
    )

    @classmethod
    def parse_plugins_file(cls, file_path: str) -> List[Dict[str, Any]]:
        if not os.path.exists(file_path):
            raise FileNotFoundError(f"File not found: {file_path}")

        with open(file_path, "r", encoding="utf-8", errors="ignore") as f:
            content = f.read()

        match = re.search(r"var\s+\$plugins\s*=\s*(\[[\s\S]*\])\s*;?", content)
        if not match:
            raise ValueError(f"Could not locate var $plugins array in {file_path}")

        raw_json = match.group(1)
        plugins_data = json.loads(raw_json)
        return plugins_data


class RecursiveJsonUnpacker:
    """
    โมดูลแกะข้อมูล JSON ที่ซ้อนทับกันหลายชั้นใน parameters (SDD-015 Section 2)
    """
    @classmethod
    def is_json_string(cls, val: Any) -> bool:
        if not isinstance(val, str):
            return False
        stripped = val.strip()
        return (stripped.startswith("{") and stripped.endswith("}")) or (stripped.startswith("[") and stripped.endswith("]"))

    @classmethod
    def unpack(cls, data: Any, current_path: List[Union[str, int]]) -> List[Tuple[List[Union[str, int]], str]]:
        results: List[Tuple[List[Union[str, int]], str]] = []

        if isinstance(data, dict):
            for k, v in data.items():
                new_path = current_path + [k]
                if cls.is_json_string(v):
                    try:
                        parsed = json.loads(v)
                        results.extend(cls.unpack(parsed, new_path))
                        continue
                    except Exception:
                        pass
                results.extend(cls.unpack(v, new_path))
        elif isinstance(data, list):
            for idx, item in enumerate(data):
                new_path = current_path + [idx]
                if cls.is_json_string(item):
                    try:
                        parsed = json.loads(item)
                        results.extend(cls.unpack(parsed, new_path))
                        continue
                    except Exception:
                        pass
                results.extend(cls.unpack(item, new_path))
        elif isinstance(data, str):
            if data.strip():
                results.append((current_path, data))

        return results


class SemanticParameterClassifier:
    """
    โมดูลคัดกรองความปลอดภัย: แยกเฉพาะ Human-Readable UI Text ออกจากโค้ดและคอนฟิก (SDD-015 Section 2 & 3)
    """
    DISALLOWED_KEY_SUFFIXES: Set[str] = {
        ":bool", ":css", ":color", ":file", ":img", ":image",
        ":variable", ":switch", ":id", ":i", ":e"
    }

    SYSTEM_KEYS_BLACKLIST: Set[str] = {
        "name", "status", "description", "folder", "filename", "skin",
        "fontFace", "formula", "renderingMode", "alwaysDash", "key",
        "right click", "show on new page", "pause until visible",
        "redZoneFillColor:str", "backColor:css", "mask", "fill", "foreground"
    }

    JAVASCRIPT_CODE_PATTERNS: List[str] = [
        r"Graphics\.", r"Window_Base\.", r"\.prototype\.",
        r"\bfunction\b", r"=>", r"[+\-*/]\s*\d+", r"===|!==|&&|\|\|",
        r"^#[0-9a-fA-F]{3,8}$", r"^rgba?\(", r"^(?:true|false|auto|left|center|right|on|off|control|shift|alt|tab|enter|escape|space|relative|absolute)$"
    ]

    ALLOWED_KEY_KEYWORDS: List[str] = [
        "Text", "Title", "Name", "Command", "Format", "Label", "Message",
        "Prompt", "Read", "Cancel", "Close", "Word", "Period", "Option",
        "morningPeriod", "dayPeriod", "eveningPeriod", "nightPeriod", "daysWeek", "months", "seasons",
        "anotherData", "anotherDataList", "mode"
    ]

    BLACK_KEY_PATTERNS: List[str] = [
        "iconname", "icon", "image", "skin", "font", "key", "position",
        "lunatic mode", "eval", "code", "switch", "variable", "folder", "filename",
        "キー", "タイプ", "座標"
    ]

    @classmethod
    def is_translatable_ui_string(cls, key_path: List[Union[str, int]], value: str) -> Tuple[bool, str]:
        val_clean = value.strip()
        if not val_clean:
            return False, "Empty string"

        path_str = ".".join(str(p) for p in key_path).lower()
        leaf_key = str(key_path[-1]) if key_path else ""
        leaf_key_lower = leaf_key.lower()

        # 1. Reject Lunatic Mode และบล็อกโค้ดสคริปต์
        if "lunatic mode" in path_str or "eval" in path_str:
            return False, "Lunatic Mode / script block"

        # 2. Reject คอมเมนต์ในโค้ด (เช่น // Variables)
        if val_clean.startswith("//") or val_clean.startswith("/*") or "console.log" in val_clean:
            return False, "Code comment or console call"

        # 3. Reject ตาม Suffix ที่ระบุชนิดตัวแปรเกม
        for sfx in cls.DISALLOWED_KEY_SUFFIXES:
            if leaf_key.endswith(sfx):
                return False, f"Key suffix '{sfx}' is engine data"

        # 4. Reject ตาม System Blacklist และ Black Keywords
        # ข้อยกเว้น: คีย์ 'name' ภายใต้ parameters เช่น daysWeek, periods, quests ให้ถือเป็น UI Text ที่ต้องแปล
        is_whitelisted_name_context = leaf_key == "name" and any(
            w in path_str for w in ["daysweek", "morningperiod", "dayperiod", "eveningperiod", "nightperiod", "period", "quest", "anotherdata", "anotherdatalist", "another"]
        )
        if leaf_key in cls.SYSTEM_KEYS_BLACKLIST and not is_whitelisted_name_context:
            return False, f"Key '{leaf_key}' is in system blacklist"
        for bk in cls.BLACK_KEY_PATTERNS:
            if bk in leaf_key_lower:
                return False, f"Key contains blacklisted term '{bk}'"

        # 5. Reject โค้ด JavaScript และสูตรคำนวณ
        for pat in cls.JAVASCRIPT_CODE_PATTERNS:
            if re.search(pat, val_clean):
                return False, f"Matches code pattern '{pat}'"
        if "this.fittingheight" in val_clean.lower() or "window_base" in val_clean.lower():
            return False, "JavaScript function call"

        # 6. Reject Format วันเวลาล้วนๆ เช่น %D %MMMM %YYYY หรือ %HH%:%mm
        if re.match(r"^[%YMDdhms:, \-_/]+$", val_clean):
            return False, "Date/time format specification"

        # 7. Reject ตัวเลขล้วน หรือสัญลักษณ์ล้วน
        if re.match(r"^[-+]?\d*\.?\d+$", val_clean):
            return False, "Numeric value"
        if re.match(r"^[\s\-_.\*~!?,:;\"'()\[\]{}|\\/]+$", val_clean):
            return False, "Pure symbols"

        # 8. กรองแท็กควบคุมเพียวๆ เช่น \c[6], \i[160]%1 (ที่ไม่มีข้อความมนุษย์อยู่เลย)
        clean_text_only = re.sub(r"\\[a-zA-Z]+(?:\[\d+\])?", "", val_clean)
        clean_text_only = re.sub(r"%\d+", "", clean_text_only)
        clean_text_only = re.sub(r"[\s\-_.\*~!?,:;\"'()\[\]{}|\\/]+", "", clean_text_only).strip()

        if not clean_text_only:
            return False, "Only control tags/format without human language"

        # 9. ต้องมีอักขระภาษาธรรมชาติอย่างน้อย 1 ตัว
        if not re.search(r"[a-zA-Z\u0E00-\u0E7F\u3040-\u309F\u30A0-\u30FF\u4E00-\u9FFF]", clean_text_only):
            return False, "No natural language letters"

        # 10. ตรวจสอบ Whitelist Keywords ใน Path หรือ Key หรือรูปแบบข้อความ RPG Maker
        has_whitelist = any(kw.lower() in leaf_key_lower or kw.lower() in path_str for kw in cls.ALLOWED_KEY_KEYWORDS)
        has_rpgm_text_marker = bool(re.search(r"(?:\\[iIcC]\[\d+\]|%\d+|Quests|Objective|Reward|Description|Subtext)", val_clean))

        if has_whitelist or has_rpgm_text_marker:
            return True, "Valid UI text"

        return False, "Unmatched general string"


class ATFPluginCSVBridge:
    """
    โมดูลแปลงข้อมูลระหว่าง Plugin Text Entities กับ CSV Schema 8 คอลัมน์ของ ATF (SDD-015 Section 2)
    """
    HEADER: List[str] = [
        "Original", "Initial", "Filename", "Row", "Note", "Role", "Speaker", "Displayable"
    ]

    @classmethod
    def format_path_string(cls, path: List[Union[str, int]]) -> str:
        tokens = []
        for p in path:
            if isinstance(p, int):
                tokens.append(f"[{p}]")
            elif " " in str(p) or "-" in str(p):
                tokens.append(f"['{p}']")
            else:
                tokens.append(f".{p}" if tokens else str(p))
        return "".join(tokens)

    @classmethod
    def export_to_csv(cls, entries: List[Dict[str, Any]], output_path: str) -> None:
        os.makedirs(os.path.dirname(os.path.abspath(output_path)), exist_ok=True)
        with open(output_path, "w", encoding="utf-8", newline="") as f:
            writer = csv.writer(f)
            writer.writerow(cls.HEADER)
            for idx, entry in enumerate(entries, start=1):
                writer.writerow([
                    entry["original"],
                    entry.get("initial", ""),
                    "plugins.js",
                    str(idx),
                    entry["note"],
                    "UI/Plugin",
                    entry["speaker"],
                    "Yes"
                ])


def extract_plugin_texts(plugins_js_path=DEFAULT_PLUGINS_JS, output_csv_path=DEFAULT_OUTPUT_CSV):
    start_t = time.time()
    print("=" * 80, flush=True)
    print("🧩 EXTRACTING RPG MAKER MV PLUGIN TEXTS (SDD-015 / SAD-013 COMPLIANT)", flush=True)
    print(f"Target JS: {plugins_js_path}", flush=True)
    print(f"Output CSV: {output_csv_path}", flush=True)
    print("=" * 80, flush=True)

    if not os.path.exists(plugins_js_path):
        print(f"❌ plugins.js not found: {plugins_js_path}", flush=True)
        return

    print("⏳ Parsing plugins.js array...", flush=True)
    plugins_data = PluginASTParser.parse_plugins_file(plugins_js_path)
    print(f"📦 Total Plugins Loaded: {len(plugins_data):,} plugins", flush=True)

    extracted_entries: List[Dict[str, Any]] = []
    skipped_count = 0

    print("⏳ Unpacking nested structures and classifying parameters...", flush=True)
    for p_idx, plugin in enumerate(plugins_data):
        plugin_name = plugin.get("name", f"Plugin_{p_idx}")
        status = plugin.get("status", False)
        parameters = plugin.get("parameters", {})

        if not parameters or not isinstance(parameters, dict):
            continue

        unpacked = RecursiveJsonUnpacker.unpack(parameters, [plugin_name, "parameters"])

        for path, val in unpacked:
            is_translatable, reason = SemanticParameterClassifier.is_translatable_ui_string(path, val)
            if is_translatable:
                note_path = ATFPluginCSVBridge.format_path_string(path)
                extracted_entries.append({
                    "original": val,
                    "initial": "",
                    "note": note_path,
                    "speaker": plugin_name
                })
            else:
                skipped_count += 1

    elapsed = time.time() - start_t
    print(f"\n📊 EXTRACTION SUMMARY (Completed in {elapsed:.2f}s):", flush=True)
    print(f"  • ข้อความ UI/Plugin ที่สกัดออกมาสำเร็จ: {len(extracted_entries):,} ข้อความ", flush=True)
    print(f"  • พารามิเตอร์โค้ด/คอนฟิก/ตัวแปรที่กรองข้ามอย่างปลอดภัย: {skipped_count:,} รายการ", flush=True)

    if extracted_entries:
        ATFPluginCSVBridge.export_to_csv(extracted_entries, output_csv_path)
        print(f"💾 Successfully exported plugin texts to: {output_csv_path}", flush=True)

        print("\n🔍 SAMPLE EXTRACTED TEXTS (First 10 entries):", flush=True)
        for idx, entry in enumerate(extracted_entries[:10], start=1):
            print(f"  [{idx}] Plugin: {entry['speaker']} | Path: {entry['note']}")
            print(f"      ORIGINAL: {repr(entry['original'])}")


