class PluginASTParser:
    """
    โมดูลจัดการการแยกและประกอบ JavaScript Wrapper สำหรับ www/js/plugins.js (SDD-015 Section 2)
    """
    HEADER_TEMPLATE: str = (
        "// Generated by RPG Maker.\n"
        "// Do not edit this file directly.\n"
        "var $plugins =\n"
    )

    @classmethod
    def parse_plugins_file(cls, file_path: str) -> List[Dict[str, Any]]:
        with open(file_path, "r", encoding="utf-8", errors="ignore") as f:
            content = f.read()

        match = re.search(r"var\s+\$plugins\s*=\s*(\[[\s\S]*\])\s*;?", content)
        if not match:
            raise ValueError(f"Could not locate var $plugins array in {file_path}")

        raw_json = match.group(1)
        return json.loads(raw_json)

    @classmethod
    def serialize_plugins_file(cls, plugins_data: List[Dict[str, Any]]) -> str:
        # จัดรูปแบบเป็น JSON อาเรย์ พร้อม Header ตามแบบฉบับของ RPG Maker MV
        formatted_json = json.dumps(plugins_data, ensure_ascii=False, indent=None)
        lines = ["// Generated by RPG Maker.", "// Do not edit this file directly.", "var $plugins =", "["]
        for idx, p in enumerate(plugins_data):
            comma = "," if idx < len(plugins_data) - 1 else ""
            lines.append(json.dumps(p, ensure_ascii=False) + comma)
        lines.append("];")
        lines.append("")
        return "\n".join(lines)


class TagParityVerifier:
    """
    โมดูลตรวจสอบความสมบูรณ์ของรหัสควบคุมเกม (%1, \i[n], \c[n]) (SDD-015 Section 6)
    """
    @classmethod
    def verify(cls, orig: str, trans: str) -> Tuple[bool, str]:
        # 1. ตรวจสอบ Format Specifiers เช่น %1, %2
        orig_formats = set(re.findall(r"%\d+", orig))
        trans_formats = set(re.findall(r"%\d+", trans))
        if orig_formats != trans_formats:
            return False, f"Format specifier mismatch: orig={orig_formats} vs trans={trans_formats}"

        # 2. ตรวจสอบ Icon & Color Tags เช่น \i[192], \c[6] (Case-insensitive)
        orig_tags = set(t.lower() for t in re.findall(r"\\[iIcC]\[\d+\]", orig))
        trans_tags = set(t.lower() for t in re.findall(r"\\[iIcC]\[\d+\]", trans))
        if orig_tags != trans_tags:
            return False, f"Control tag mismatch: orig={orig_tags} vs trans={trans_tags}"

        return True, "Parity Verified"


class RecursiveJsonPacker:
    """
    โมดูลฉีดคำแปลและประกอบ JSON String ที่ซ้อนทับกลับสู่ระดับเดิม (SDD-015 Section 2)
    """
    @classmethod
    def parse_path_tokens(cls, path_str: str) -> List[Union[str, int]]:
        tokens: List[Union[str, int]] = []
        raw_tokens = re.findall(r"([^.\[\]'\"]+|\[\d+\]|\['[^']+'\])", path_str)
        for t in raw_tokens:
            if t.startswith("[") and t.endswith("]"):
                inner = t[1:-1]
                if inner.isdigit():
                    tokens.append(int(inner))
                elif inner.startswith("'") and inner.endswith("'"):
                    tokens.append(inner[1:-1])
                else:
                    tokens.append(inner)
            else:
                tokens.append(t)
        return tokens

    @classmethod
    def inject_nested(cls, container: Any, remaining_path: List[Union[str, int]], new_val: str) -> bool:
        if not remaining_path:
            return False

        key = remaining_path[0]

        if len(remaining_path) == 1:
            if isinstance(container, dict) and key in container:
                container[key] = new_val
                return True
            elif isinstance(container, list) and isinstance(key, int) and 0 <= key < len(container):
                container[key] = new_val
                return True
            return False

        sub_item = None
        if isinstance(container, dict) and key in container:
            sub_item = container[key]
        elif isinstance(container, list) and isinstance(key, int) and 0 <= key < len(container):
            sub_item = container[key]
        else:
            return False

        if isinstance(sub_item, str) and (sub_item.strip().startswith("{") or sub_item.strip().startswith("[")):
            try:
                parsed_sub = json.loads(sub_item)
                success = cls.inject_nested(parsed_sub, remaining_path[1:], new_val)
                if success:
                    container[key] = json.dumps(parsed_sub, ensure_ascii=False)
                    return True
            except Exception:
                pass

        if isinstance(sub_item, (dict, list)):
            return cls.inject_nested(sub_item, remaining_path[1:], new_val)

        return False


class AtomicPersistenceManager:
    """
    โมดูลจัดการการบันทึกไฟล์แบบ Atomic พร้อมสร้าง Timestamped Backup
    """
    @staticmethod
    def create_timestamped_backup(file_path: str, suffix: str = "backup_plugin") -> str:
        if not os.path.exists(file_path):
            return ""
        now_str = datetime.datetime.now().strftime("%Y%m%d_%H%M%S")
        ext = os.path.splitext(file_path)[1]
        bak_path = f"{file_path}.{suffix}_{now_str}{ext}"
        shutil.copy2(file_path, bak_path)
        return bak_path

    @staticmethod
    def atomic_write(file_path: str, text_content: str) -> None:
        temp_file = f"{file_path}.tmp"
        with open(temp_file, "w", encoding="utf-8") as f:
            f.write(text_content)
            f.flush()
            os.fsync(f.fileno())
        os.replace(temp_file, file_path)


def normalize_control_codes(text: str) -> str:
    """
    แปลง XML Semantic Tags กลับเป็น Native RPG Maker MV Escape Codes
    """
    if not text:
        return text
    res = text
    res = re.sub(r"\\?<color id=[\"']?(\d+)[\"']?>(.*?)\\?</color>", r"\\c[\1]\2\\c[0]", res, flags=re.DOTALL)
    res = re.sub(r"\\?<bold>(.*?)\\?</bold>", r"\\fb\1\\fb", res, flags=re.DOTALL)
    res = re.sub(r"\\?<italic>(.*?)\\?</italic>", r"\\fi\1\\fi", res, flags=re.DOTALL)
    res = re.sub(r"\\?<icon id=[\"']?(\d+)[\"']?\s*\/?>", r"\\I[\1]", res, flags=re.IGNORECASE)
    res = re.sub(r"\\?<\s*pause_quarter\s*\/?>", r"\.", res, flags=re.IGNORECASE)
    res = re.sub(r"\\?<\s*pause_second\s*\/?>", r"\|", res, flags=re.IGNORECASE)
    res = re.sub(r"\\?<\s*wait_input\s*\/?>", r"\!", res, flags=re.IGNORECASE)
    return res


def inject_plugin_texts(plugins_js_path=DEFAULT_PLUGINS_JS, csv_path=DEFAULT_INPUT_CSV, dry_run=False):
    start_t = time.time()
    print("=" * 80, flush=True)
    print("💉 INJECTING TRANSLATED PLUGIN TEXTS (SDD-015 / SAD-013 COMPLIANT)", flush=True)
    print(f"Target JS: {plugins_js_path}", flush=True)
    print(f"Input CSV: {csv_path}", flush=True)
    print(f"Mode: {'DRY RUN (Simulation only)' if dry_run else 'LIVE INJECTION (Modifying plugins.js)'}", flush=True)
    print("=" * 80, flush=True)

    if not os.path.exists(plugins_js_path):
        print(f"❌ plugins.js not found: {plugins_js_path}", flush=True)
        return
    if not os.path.exists(csv_path):
        print(f"❌ Plugin CSV not found: {csv_path}", flush=True)
        return

    # 1. โหลดคำแปลจาก CSV
    print("⏳ Loading translated rows from CSV...", flush=True)
    translations: List[Dict[str, str]] = []
    with open(csv_path, "r", encoding="utf-8", errors="ignore") as f:
        reader = csv.reader(f)
        header = next(reader)
        for row in reader:
            if len(row) >= 5:
                orig = row[0]
                init = row[1]
                note = row[4]
                if init.strip() and init.strip() != orig.strip():
                    translations.append({
                        "orig": orig,
                        "init": normalize_control_codes(init),
                        "path": note
                    })

    print(f"📦 Loaded {len(translations):,} active translations ready for injection.", flush=True)
    if not translations:
        print("💡 No translations found (Initial is empty or identical to Original). Nothing to inject.")
        return

    # 2. โหลด plugins.js
    plugins_data = PluginASTParser.parse_plugins_file(plugins_js_path)
    plugins_by_name = {p.get("name", ""): p for p in plugins_data}

    injected_count = 0
    parity_failed_count = 0
    examples = []

    print("⏳ Injecting translations into nested parameters...", flush=True)
    for t_item in translations:
        orig = t_item["orig"]
        init = t_item["init"]
        path_str = t_item["path"]

        # ตรวจสอบ Tag Parity
        is_safe, parity_msg = TagParityVerifier.verify(orig, init)
        if not is_safe:
            print(f"⚠️ Tag Parity Warning for {path_str}: {parity_msg} (Skipping to preserve game stability)", flush=True)
            parity_failed_count += 1
            continue

        tokens = RecursiveJsonPacker.parse_path_tokens(path_str)
        if not tokens:
            continue

        plugin_name = tokens[0]
        if plugin_name not in plugins_by_name:
            continue

        target_plugin = plugins_by_name[plugin_name]
        parameters = target_plugin.get("parameters", {})

        inner_tokens = tokens[1:]
        if inner_tokens and inner_tokens[0] == "parameters":
            inner_tokens = inner_tokens[1:]

        success = RecursiveJsonPacker.inject_nested(parameters, inner_tokens, init)
        if success:
            injected_count += 1
            if len(examples) < 5:
                examples.append((path_str, orig, init))

    elapsed = time.time() - start_t
    print(f"\n📊 INJECTION SUMMARY (Completed in {elapsed:.2f}s):", flush=True)
    print(f"  • ข้อความที่ฉีดคำแปลสำเร็จ (Successfully Injected): {injected_count:,} รายการ", flush=True)
    print(f"  • ข้อความที่ถูกระงับเนื่องจากแท็กควบคุมไม่ตรง (Parity Guard): {parity_failed_count:,} รายการ", flush=True)

    if examples:
        print("\n🔍 SAMPLE INJECTIONS (First 5 entries):", flush=True)
        for path_str, orig, init in examples:
            print(f"  Path: {path_str}")
            print(f"    ORIG: {repr(orig)}")
            print(f"    THAI: {repr(init)}")

    if dry_run:
        print("\n💡 This was a DRY RUN (Simulation). No files were modified on disk.", flush=True)
        print("   To apply changes for real, run without --dry-run", flush=True)
    else:
        print("\n💾 Committing changes to disk via Atomic Persistence...", flush=True)
        bak_file = AtomicPersistenceManager.create_timestamped_backup(plugins_js_path, suffix="backup_plugin")
        print(f"  • Created backup plugins.js at: {bak_file}", flush=True)

        serialized_js = PluginASTParser.serialize_plugins_file(plugins_data)
        AtomicPersistenceManager.atomic_write(plugins_js_path, serialized_js)
        print(f"  • Successfully patched and updated: {plugins_js_path}", flush=True)
        print("🎉 PLUGIN LOCALIZATION INJECTION COMPLETED SUCCESSFULLY 100%!", flush=True)


